// Package openapigen generates the typed SilkSpool API client from the OpenAPI spec.
//
//go:generate go run ./main -spec ../../api/openapi.yaml -out ../../pkg/apiclient/client.gen.go
package openapigen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

type spec struct {
	OpenAPI    string              `yaml:"openapi"`
	Info       specInfo            `yaml:"info"`
	Paths      map[string]pathItem `yaml:"paths"`
	Components specComponents      `yaml:"components"`
}

type specInfo struct {
	Title   string `yaml:"title"`
	Version string `yaml:"version"`
}

type specComponents struct {
	Parameters map[string]parameter `yaml:"parameters"`
	Responses  map[string]response  `yaml:"responses"`
	Schemas    map[string]schema    `yaml:"schemas"`
}

type pathItem struct {
	Parameters []parameter `yaml:"parameters"`
	Get        *operation  `yaml:"get"`
	Post       *operation  `yaml:"post"`
	Put        *operation  `yaml:"put"`
	Delete     *operation  `yaml:"delete"`
}

type operation struct {
	OperationID string              `yaml:"operationId"`
	Summary     string              `yaml:"summary"`
	Parameters  []parameter         `yaml:"parameters"`
	RequestBody *requestBody        `yaml:"requestBody"`
	Responses   map[string]response `yaml:"responses"`
}

type parameter struct {
	Ref      string `yaml:"$ref"`
	Name     string `yaml:"name"`
	In       string `yaml:"in"`
	Required bool   `yaml:"required"`
	Schema   schema `yaml:"schema"`
}

type requestBody struct {
	Required bool                 `yaml:"required"`
	Content  map[string]mediaType `yaml:"content"`
}

type response struct {
	Ref     string               `yaml:"$ref"`
	Content map[string]mediaType `yaml:"content"`
}

type mediaType struct {
	Schema schema `yaml:"schema"`
}

type schema struct {
	Ref                  string            `yaml:"$ref"`
	Type                 string            `yaml:"type"`
	Format               string            `yaml:"format"`
	Items                *schema           `yaml:"items"`
	AdditionalProperties *schema           `yaml:"additionalProperties"`
	Properties           map[string]schema `yaml:"properties"`
	Required             []string          `yaml:"required"`
	Enum                 []string          `yaml:"enum"`
	Description          string            `yaml:"description"`
}

type generator struct {
	spec      spec
	imports   map[string]bool
	typeNames map[string]string
}

// Generate renders the Go client source for the given OpenAPI YAML.
func Generate(specData []byte) ([]byte, error) {
	var parsed spec
	if err := yaml.Unmarshal(specData, &parsed); err != nil {
		return nil, fmt.Errorf("parse OpenAPI spec: %w", err)
	}
	if parsed.OpenAPI == "" || len(parsed.Paths) == 0 {
		return nil, fmt.Errorf("OpenAPI spec is missing openapi/paths")
	}
	g := &generator{spec: parsed, imports: map[string]bool{}, typeNames: map[string]string{}}
	for name := range parsed.Components.Schemas {
		g.typeNames[refName("#/components/schemas/"+name)] = goTypeName(name)
	}
	var body bytes.Buffer
	body.WriteString("// Code generated by internal/openapigen; DO NOT EDIT.\n\n")
	body.WriteString("package apiclient\n\n")

	// Generate code first so imports are known.
	var code bytes.Buffer
	code.WriteString(fmt.Sprintf("const APIVersion = %q\n\n", parsed.Info.Version))
	g.generatePathConstants(&code)
	code.WriteString("// Client is a typed client generated from api/openapi.yaml.\n")
	code.WriteString("type Client struct {\n")
	code.WriteString("\tBaseURL string\n")
	code.WriteString("\tHTTPClient *http.Client\n")
	code.WriteString("\tToken string\n")
	code.WriteString("}\n\n")
	code.WriteString("func (c *Client) client() *http.Client {\n")
	code.WriteString("\tif c.HTTPClient != nil {\n\t\treturn c.HTTPClient\n\t}\n\treturn http.DefaultClient\n}\n\n")
	if err := g.generateSchemas(&code); err != nil {
		return nil, err
	}
	if err := g.generateOperations(&code); err != nil {
		return nil, err
	}

	body.WriteString("import (\n")
	for _, imp := range g.sortedImports() {
		body.WriteString("\t\"" + imp + "\"\n")
	}
	body.WriteString(")\n\n")
	body.Write(code.Bytes())
	formatted, err := format.Source(body.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated client: %w\n%s", err, body.String())
	}
	return formatted, nil
}

func (g *generator) sortedImports() []string {
	imports := make([]string, 0, len(g.imports))
	for imp := range g.imports {
		imports = append(imports, imp)
	}
	sort.Strings(imports)
	return imports
}

func (g *generator) generatePathConstants(code *bytes.Buffer) {
	code.WriteString("// Paths from the OpenAPI document.\nconst (\n")
	paths := sortedKeys(g.spec.Paths)
	for _, path := range paths {
		name := "Path" + goTypeName(strings.NewReplacer("/", " ", "{", " ", "}", " ", "-", " ").Replace(path))
		code.WriteString(fmt.Sprintf("\t%s = %q\n", name, path))
	}
	code.WriteString(")\n\n")
}

func (g *generator) generateSchemas(code *bytes.Buffer) error {
	names := sortedKeys(g.spec.Components.Schemas)
	for _, name := range names {
		schema := g.spec.Components.Schemas[name]
		if schema.Type != "" && schema.Type != "object" {
			continue
		}
		code.WriteString(fmt.Sprintf("// %s is generated from components.schemas.%s.\n", goTypeName(name), name))
		code.WriteString(fmt.Sprintf("type %s struct {\n", goTypeName(name)))
		required := map[string]bool{}
		for _, field := range schema.Required {
			required[field] = true
		}
		props := sortedKeys(schema.Properties)
		for _, prop := range props {
			field := schema.Properties[prop]
			goType, err := g.goType(field)
			if err != nil {
				return fmt.Errorf("schema %s.%s: %w", name, prop, err)
			}
			tag := prop
			if !required[prop] {
				tag += ",omitempty"
			}
			comment := strings.TrimSpace(field.Description)
			if comment != "" {
				code.WriteString("\t// " + strings.ReplaceAll(comment, "\n", " ") + "\n")
			}
			code.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\"`\n", goFieldName(prop), goType, tag))
		}
		code.WriteString("}\n\n")
	}
	return nil
}

func (g *generator) generateOperations(code *bytes.Buffer) error {
	for _, path := range sortedKeys(g.spec.Paths) {
		item := g.spec.Paths[path]
		operations := []struct {
			method string
			op     *operation
		}{
			{"GET", item.Get},
			{"POST", item.Post},
			{"PUT", item.Put},
			{"DELETE", item.Delete},
		}
		for _, entry := range operations {
			if entry.op == nil {
				continue
			}
			if err := g.generateOperation(code, path, entry.method, item.Parameters, entry.op); err != nil {
				return err
			}
		}
	}
	return nil
}

func (g *generator) generateOperation(code *bytes.Buffer, path, method string, pathParams []parameter, op *operation) error {
	if op.OperationID == "" {
		return fmt.Errorf("%s %s: operationId is required", method, path)
	}
	params, err := g.resolveParameters(pathParams, op.Parameters)
	if err != nil {
		return err
	}
	responseSchema, err := g.successSchema(op.Responses)
	if err != nil {
		return err
	}
	responseType := "struct{}"
	if responseSchema != nil {
		responseType, err = g.goType(*responseSchema)
		if err != nil {
			return err
		}
	}
	if responseType == "interface{}" {
		responseType = "map[string]interface{}"
	}
	bodyType := ""
	if op.RequestBody != nil {
		bodyType, err = g.bodyType(*op.RequestBody)
		if err != nil {
			return err
		}
	}

	methodName := goTypeName(op.OperationID)
	code.WriteString(fmt.Sprintf("// %s implements %s %s.\n", methodName, method, path))
	code.WriteString(fmt.Sprintf("func (c *Client) %s(ctx context.Context", methodName))
	for _, param := range params {
		code.WriteString(", " + param.argName + " " + param.argType)
	}
	if bodyType != "" {
		code.WriteString(", body " + bodyType)
	}
	code.WriteString(fmt.Sprintf(") (*%s, error) {\n", responseType))

	code.WriteString(fmt.Sprintf("\tpath := %q\n", path))
	for _, param := range params {
		if param.in != "path" {
			continue
		}
		code.WriteString(fmt.Sprintf("\tpath = strings.ReplaceAll(path, %q, url.PathEscape(%s))\n", "{"+param.name+"}", param.argName))
	}
	queryParams := make([]generatedParam, 0)
	for _, param := range params {
		if param.in == "query" {
			queryParams = append(queryParams, param)
		}
	}
	if len(queryParams) > 0 {
		code.WriteString("\tquery := url.Values{}\n")
		for _, param := range queryParams {
			if strings.Contains(param.argType, "bool") || strings.Contains(param.argType, "int") || strings.Contains(param.argType, "float") {
				g.imports["strconv"] = true
			}
			if param.optional {
				code.WriteString(fmt.Sprintf("\tif %s != nil {\n", param.argName))
			}
			valueExpr := param.argName
			if param.optional {
				valueExpr = "*" + param.argName
			}
			code.WriteString(fmt.Sprintf("\t\tquery.Set(%q, %s)\n", param.name, queryValueExpr(param.argType, valueExpr)))
			if param.optional {
				code.WriteString("\t}\n")
			}
		}
		code.WriteString("\tif encoded := query.Encode(); encoded != \"\" {\n\t\tpath += \"?\" + encoded\n\t}\n")
	}

	code.WriteString("\tvar requestBody io.Reader\n")
	if bodyType != "" {
		code.WriteString("\tencodedBody, err := json.Marshal(body)\n")
		code.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		code.WriteString("\trequestBody = bytes.NewReader(encodedBody)\n")
	}
	code.WriteString(fmt.Sprintf("\trequest, err := http.NewRequestWithContext(ctx, http.Method%s, c.BaseURL+path, requestBody)\n", goTypeName(strings.ToLower(method))))
	code.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	if bodyType != "" {
		code.WriteString("\trequest.Header.Set(\"Content-Type\", \"application/json\")\n")
	}
	code.WriteString("\tif c.Token != \"\" {\n\t\trequest.Header.Set(\"Authorization\", \"Bearer \"+c.Token)\n\t}\n")
	code.WriteString("\tresponse, err := c.client().Do(request)\n")
	code.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	code.WriteString("\tdefer response.Body.Close()\n")
	code.WriteString("\tif response.StatusCode < 200 || response.StatusCode >= 300 {\n")
	code.WriteString("\t\tvar apiError ErrorResponse\n")
	code.WriteString("\t\tif decodeErr := json.NewDecoder(response.Body).Decode(&apiError); decodeErr == nil && apiError.Error.Message != \"\" {\n")
	code.WriteString(fmt.Sprintf("\t\t\treturn nil, fmt.Errorf(%q, apiError.Error.Code, apiError.Error.Message)\n", method+" "+path+": %s: %s"))
	code.WriteString("\t\t}\n")
	code.WriteString(fmt.Sprintf("\t\treturn nil, fmt.Errorf(%q, response.StatusCode)\n", method+" "+path+": HTTP %d"))
	code.WriteString("\t}\n")
	code.WriteString(fmt.Sprintf("\tvar result %s\n", responseType))
	code.WriteString("\tif err := json.NewDecoder(response.Body).Decode(&result); err != nil {\n\t\treturn nil, err\n\t}\n")
	code.WriteString("\treturn &result, nil\n")
	code.WriteString("}\n\n")
	g.imports["bytes"] = true
	g.imports["context"] = true
	g.imports["encoding/json"] = true
	g.imports["fmt"] = true
	g.imports["io"] = true
	g.imports["net/http"] = true
	g.imports["net/url"] = true
	g.imports["strings"] = true
	return nil
}

type generatedParam struct {
	name     string
	in       string
	argName  string
	argType  string
	optional bool
}

func (g *generator) resolveParameters(pathParams, opParams []parameter) ([]generatedParam, error) {
	all := make([]parameter, 0, len(pathParams)+len(opParams))
	all = append(all, pathParams...)
	all = append(all, opParams...)
	seen := map[string]bool{}
	result := make([]generatedParam, 0, len(all))
	for _, param := range all {
		if param.Ref != "" {
			name := refName(param.Ref)
			resolved, ok := g.spec.Components.Parameters[name]
			if !ok {
				return nil, fmt.Errorf("unknown parameter ref %s", param.Ref)
			}
			param = resolved
		}
		if param.Name == "" || param.In == "" {
			continue
		}
		key := param.In + ":" + param.Name
		if seen[key] {
			continue
		}
		seen[key] = true
		goType, err := g.goType(param.Schema)
		if err != nil {
			return nil, err
		}
		optional := !param.Required
		if param.In == "path" {
			optional = false
			if goType != "string" {
				goType = "string"
			}
		}
		if param.In == "query" && optional {
			goType = "*" + goType
		}
		result = append(result, generatedParam{
			name:     param.Name,
			in:       param.In,
			argName:  goFieldName(param.Name),
			argType:  goType,
			optional: optional && param.In == "query",
		})
	}
	return result, nil
}

func (g *generator) successSchema(responses map[string]response) (*schema, error) {
	statuses := make([]string, 0, len(responses))
	for status := range responses {
		if len(status) > 0 && status[0] == '2' {
			statuses = append(statuses, status)
		}
	}
	sort.Strings(statuses)
	if len(statuses) == 0 {
		return nil, nil
	}
	resp := responses[statuses[0]]
	if resp.Ref != "" {
		name := refName(resp.Ref)
		resolved, ok := g.spec.Components.Responses[name]
		if !ok {
			return nil, fmt.Errorf("unknown response ref %s", resp.Ref)
		}
		resp = resolved
	}
	content, ok := resp.Content["application/json"]
	if !ok {
		return nil, nil
	}
	return &content.Schema, nil
}

func (g *generator) bodyType(body requestBody) (string, error) {
	content, ok := body.Content["application/json"]
	if !ok {
		return "", fmt.Errorf("requestBody must declare application/json")
	}
	return g.goType(content.Schema)
}

func (g *generator) goType(value schema) (string, error) {
	if value.Ref != "" {
		name := refName(value.Ref)
		goName, ok := g.typeNames[value.Ref]
		if !ok {
			goName = goTypeName(name)
			g.typeNames[value.Ref] = goName
		}
		return goName, nil
	}
	switch value.Type {
	case "":
		return "interface{}", nil
	case "object":
		if value.AdditionalProperties != nil {
			inner, err := g.goType(*value.AdditionalProperties)
			if err != nil {
				return "", err
			}
			return "map[string]" + inner, nil
		}
		if len(value.Properties) > 0 {
			return "map[string]interface{}", nil
		}
		return "map[string]interface{}", nil
	case "array":
		if value.Items == nil {
			return "[]interface{}", nil
		}
		inner, err := g.goType(*value.Items)
		if err != nil {
			return "", err
		}
		return "[]" + inner, nil
	case "integer":
		return "int", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "string":
		return "string", nil
	default:
		return "", fmt.Errorf("unsupported schema type %q", value.Type)
	}
}

func queryValueExpr(goType, expr string) string {
	switch goType {
	case "*bool":
		return "strconv.FormatBool(" + expr + ")"
	case "*int":
		return "strconv.Itoa(" + expr + ")"
	case "*float64":
		return "strconv.FormatFloat(" + expr + ", 'f', -1, 64)"
	case "string":
		return expr
	case "bool":
		return "strconv.FormatBool(" + expr + ")"
	case "int":
		return "strconv.Itoa(" + expr + ")"
	case "float64":
		return "strconv.FormatFloat(" + expr + ", 'f', -1, 64)"
	default:
		return "fmt.Sprint(" + expr + ")"
	}
}

func refName(ref string) string {
	if idx := strings.LastIndex(ref, "/"); idx >= 0 {
		return ref[idx+1:]
	}
	return ref
}

func goTypeName(value string) string {
	parts := strings.FieldsFunc(value, func(r rune) bool {
		return r == '_' || r == '-' || r == '/' || r == ' ' || r == '{' || r == '}' || r == '.'
	})
	var out strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		out.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	result := out.String()
	switch result {
	case "Id":
		return "ID"
	case "Url":
		return "URL"
	case "ApiUrl":
		return "APIURL"
	}
	return result
}

func goFieldName(value string) string {
	name := goTypeName(value)
	switch name {
	case "Id":
		return "ID"
	case "Url":
		return "URL"
	}
	if strings.HasSuffix(name, "Id") {
		return strings.TrimSuffix(name, "Id") + "ID"
	}
	if strings.HasSuffix(name, "Url") {
		return strings.TrimSuffix(name, "Url") + "URL"
	}
	return name
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
